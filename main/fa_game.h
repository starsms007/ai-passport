//
// ★ 2026-09-19 三叶草收入改成「逐档点名」的固定值，**不再有 0~1 的随机浮动**：
//       试玩 15 秒  0 棵   ← 用户明确要求「试玩的 15 秒不给三叶草」
//       5 分钟      1 棵
//       1 小时      2 棵
//       4 小时      3 棵
//       12 小时     5 棵
//   为什么必须去掉浮动：用户是逐档报的数字。留着浮动就会出现「说好 1 棵给了 2 棵」
