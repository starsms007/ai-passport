// main/fa_game.h —— 《去远方》玩法逻辑层
//
// 纯数据 + 纯函数，**不 include lvgl.h**。这样做的价值：
//   1. 可以在 app_main 的启动自检里把整局玩法跑一遍（真机跑不了单元测试，
//      但逻辑层没有 GUI 依赖，就能压缩时间跑模拟）。
//   2. 界面怎么改都不会碰到存档结构和奖励规则。
//
// 玩法（旅行青蛙式收集）：
//   猫在家 → 选一个旅行时长 → 出发 → 真实时间倒计时 → 归来
//   归来带回：三叶草（按时长给）+ 大概率一张新明信片 + 小概率一件纪念品
//   24 个中国景点各有一张明信片，集满即毕业。
