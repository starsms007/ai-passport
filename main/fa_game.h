#define FA_SOUV_COUNT  24
const char *fa_souv_name(int i);

typedef enum {
    FA_HOME = 0,   // 在家，可以出发
    FA_AWAY,       // 旅行中（真实时间倒计时）
    FA_BACK,       // 刚回来，等玩家收下收获
} fa_state_t;

// ★ 存档结构。改动字段顺序/类型会让老存档读不出来 —— 由 FA_SAVE_VER 兜住。
typedef struct {
    uint16_t magic;        // FA_SAVE_MAGIC
    uint16_t ver;          // FA_SAVE_VER
    uint8_t  state;        // fa_state_t
    uint8_t  slot;         // 选中的档位
    uint8_t  tbase;        // 出发时用的时间基准（见 fa_now），0=不合法
    // 归来收获的标记（三个 bit 各有各的意思，界面层按位取用）：
    //   bit0 = **这趟带回来一张明信片**（不论新旧）—— 收获卡据此贴真图；
    //   bit1 = 这趟是花三叶草提前回来的（换掉那行三叶草文案）；
    //   bit2 = ★ 第五次新增：这张明信片**早就有了**（本档全拿到之后又抽到一张）。
    //          界面层用它在按钮那行写「这张已经有了」，而不是「● 收下」。
    uint8_t  got_flags;
    uint8_t  got_dest;     // 归来带的是哪个景点
    uint8_t  got_souv;     // 归来带的纪念品序号，255 = 没带
    uint16_t got_clover;   // 归来带回的三叶草
    uint16_t clover;       // 三叶草余额
    uint32_t depart;       // 出发时刻
    uint32_t arrive;       // 预定归来时刻
    uint32_t postcards;    // 24 位，拿到过的景点
    uint32_t souvenirs;    // 24 位，拿到过的纪念品（第四十七轮由 12 位扩到 24）
    uint32_t trips;        // 累计出行次数
} fa_save_t;

#define FA_SAVE_MAGIC  0x4641   // 'F','A'
#define FA_SAVE_VER    1

extern fa_save_t g_fa;

// ---- 生命周期 ----
void fa_init(void);              // 读存档。（没有可靠时间就取消在途旅行，理由见 .c）
void fa_save_now(void);          // 立刻写 NVS

// ---- 时间 ----
// 返回当前时刻，并把用的时间基准写进 *base_out（0 = 无效）。
//   基准 1：系统 wall clock（tb_clock 对过时 / 从 NVS 恢复过）
//   基准 2：开机秒数（刚出厂、从没对过时）
// 两个基准不能混用 —— 一旦中途对上时，基准会从 2 跳到 1，
// 用旧基准记的出发时刻再减就会得出天文数字。fa_poll() 靠比对这个值兜住。
uint32_t fa_now(uint8_t *base_out);

// ---- 操作 ----
void fa_depart(void);            // 出发（沿用 g_fa.slot）
bool fa_poll(void);              // 每帧调一次；返回 true 表示状态翻转了
void fa_recall(void);            // 提前召回：立刻归来，但拿不到新明信片
void fa_claim(void);             // 收下收获 -> 回 HOME
void fa_set_slot(int slot);      // 换档位

// ---- 三叶草快速返回（2026-09-19）----
// ★ 为什么要有这一套：原来的 fa_recall() 是**免费**的提前召回，只挂在「长按 ●」上。
//   免费意味着没有任何取舍，三叶草对它毫无影响 —— 实机反馈「三叶草有什么用」
//   有一半是这里来的。现在改成：想立刻回家，就得拿三叶草换。
//
//   定价按**剩余时长**（不是档位）—— 离到达越远，越贵：
//       试玩档（15 秒）      免费   ← 上手那一趟，不该罚
//       剩余 ≤ 5 分钟        1 个   ← 5 分钟档全程都落在这一档
//       剩余 ≤ 30 分钟       2 个
//       剩余 ≤ 1 小时        3 个
//       剩余 ≤ 4 小时       10 个   ← 第十一轮改价（原 4）
//       剩余 ≤ 12 小时      30 个   ← 第十一轮改价（原并进「更长 5」）
//       更长                30 个   ← 兜底，12 时是长度上限，正常到不了
//
//   ★★ 2026-09-19（第十一轮）用户点名改价，原话：
//        「4小时要用10个猫罐头，12小时要用30个猫罐头。」
//      这两档是**用户给定的锚点**（都正好是每小时 2.5 个），不是估出来的。
//      低三档保持原值 1/2/3 —— 连起来是一条「每小时单价随时间下降」的曲线
//      （12/h → 4/h → 3/h → 2.5/h），量越大越便宜。
//      **别再按比例去"修"低档**：5 分钟档收 1 个是上手价，1 已经是最小正整数。
//      ⚠ 表在 fa_game.c 的 RECALL_TIER，改一边必须改另一边。
//      ⚠ 为什么敢收 30：5 分钟档能刷 36 个/小时，30 个 ≈ 50 分钟的往返或小游戏，
//        换最多 12 小时的行程，这个交换成立（见交付页的集卡耗时测算）。
//
//   ★ 2026-09-19 第二次修正（用户口径）：召回的收获**照给明信片和纪念品，
//     但不给三叶草** —— 原话「相当于用三叶草买的道具」。
//     所以这趟的净变化 = −报价，同时照常抽一张本档明信片 + 25% 一件纪念品。
//     （上一版是「什么也不给」，太严 —— 花 4 棵回来一趟空手，那 4 棵花得没道理。）
//     ⚠ 报价与「本档已集满」的折价补偿是两回事：集满时的 +2 棵补偿在召回这趟
//       不发（见 fa_game.c 的 fa_finish），否则报价和余额又会对不上。
//   （原 fa_recall() 保留，给启动自检和内部兜底用；玩家走的是下面这两个。）
int  fa_recall_cost(void);       // 现在快速返回要花几棵；-1 = 当前不能召回
bool fa_recall_paid(void);       // 扣三叶草并立刻返回；三叶草不够 / 状态不对 -> false

// ---- 小游戏奖励（2026-09-19 第十轮新增）----
// ★ 这是**唯一**一条不经过行程结算就发猫罐头的通路（收藏册里那个「接猫罐头」小游戏用）。
//   走它、而不是让界面层直接改 g_fa.clover，有两个理由：
