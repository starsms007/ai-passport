// main/tb_prefs.h
// 少量持久化偏好。目前只有一项:屏幕方向。
#pragma once

// 当前屏幕方向,0/90/180/270。默认 90(横屏)。
// 这是"编译期我验不了真机朝向"的兜底 —— 上机后如果画面是倒的,
// 进设置页切一下就会存进 NVS,以后开机直接用,不用重刷固件。
int  tb_screen_deg(void);

// 设置并立即应用(写 NVS)。返回实际生效的方向。
int  tb_screen_deg_set(int deg);

// 屏幕背光亮度,10..100(%)。默认 100。
// ★ 亮度和方向一样,是「编译期验不了真机」的东西:不同批次的屏亮度差别很大,
//   白天户外和夜里关灯要的亮度也不是一个值。所以给它留了持久化的口子,
//   在收集册里可以直接调,调完写 NVS,下次开机照旧。
int  tb_bright(void);
int  tb_bright_set(int percent);   // 夹到 10..100,应用并写 NVS,返回实际值

// 必须在 bsp_lvgl_init() 之后、建任何界面之前调用:
// 从 NVS 读方向并应用,保证后续布局按正确的分辨率算。
// 顺带把亮度也贴上去(见 .c —— 开机时 main.c 那句 bsp_display_backlight(100)
// 会被这里的存档值覆盖,不然用户调过的亮度每次开机都被打回 100)。
void tb_prefs_apply(void);
