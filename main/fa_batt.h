// main/fa_batt.h —— CW2017 电量计的自愈看护
//
// ★★ 为什么要有这个模块（2026-09-28，用户报「电量数字待机后消失、重启不回」）：
//
//   设备实际跑的是**官方版** bsp_battery.c（09-22 为「components/bsp 与官方
//   逐字节一致」整体换上去的）。那一版的初始化很脆：
//     唤醒 -> 校验/重写 80 字节 profile -> 等 SOC 最多 5 秒，
//     **任何一步失败就把设备句柄置空，而且永不再试**。
//   而 bsp_battery_init() 只在 main.c 开机调一次 ⇒
//     · 一次 init 失败 = 整机运行期间电量那一格永远是空的；
//     · 现象正是「数字消失、只剩一张默认满格图标」——
//       因为 batt_show() 读不到时只清数字、从不碰图标（那是创建时的默认图）；
//     · **重启也不恢复** —— 电量计由电池供电，MCU 复位根本不复位它，
//       每次开机栽在同一处。
//   （旧固件用的是自研简化版驱动：写 CONFIG=0x00 唤醒 + 等 300ms，
//     超时也不算失败 ⇒ 几乎不会失败。所以这是升级引入的回归。）
//
// ★ 本模块**不动 components/bsp/ 一个字节**。它靠的是官方 API 自己的语义：
//   bsp_battery_init() 第一行是 `if (s_dev) return ESP_OK;`，而失败路径
//   一律 i2c_master_bus_rm_device() + s_dev=NULL ⇒ **句柄为空时再调一次，
//   就是完整重跑一遍初始化**。于是「自愈」不需要改驱动，只需要重试。
#pragma once

#include <stdbool.h>

// 启动看护任务（幂等；在 fa_view_init 里调一次）。
// 任务优先级低于 LVGL，且 99% 的时间在 delay，只在被请求时才动手。
void fa_batt_guard_start(void);

// 请求一次自愈。非阻塞：只置一个标志就返回，真正的活由看护任务干。
// ★ 内部按最小间隔限频 —— 芯片真算不出 SOC 时，bsp_battery_init() 每次
//   都要白等 5 秒，不能让 UI 侧每 10 秒请求一次。
void fa_batt_request_recover(void);

// ★★ 串行化用的**非阻塞**锁。读电量与自愈必须互斥：
//   bsp_battery.c 内部失败时那句 i2c_master_bus_rm_device(s_dev) 会释放
//   设备句柄；若此刻 LVGL 任务正拿着同一个句柄做 transmit_receive，
//   就是 use-after-free。
// ★ 用 try-lock（超时 0）：UI 侧拿不到锁就**跳过这一轮**（保留上次数字），
//   绝不等待 —— 自愈最长 5 秒，让 LVGL 任务在互斥量上等 5 秒 = 整屏定格。
bool fa_batt_try_lock(void);
void fa_batt_unlock(void);

// ★★ 2026-09-28（r55）一次「可信读数」的结果。**三种状态必须分开** ——
//   只分「读到 / 读不到」两态会引出两个 bug，当天都真踩到了：
//     · 把 WARMING 当成 FAIL ⇒ 芯片一重启就触发自愈，自愈又重启芯片 ⇒ 死循环；
//     · 把 WARMING 当成 OK   ⇒ 界面显示一个假的「红 0%」。
typedef enum {
    FA_BATT_OK = 0,     // 可信：soc 是 0..100 的有效值
    FA_BATT_WARMING,    // 芯片刚重启、SOC 还没算完 —— **不是故障**，只等
    FA_BATT_FAIL,       // 读不到（I2C 失败 / 芯片不应答 / 读到 0xFF）—— 该自愈
} fa_batt_state_t;

// ★★ 读一次电量，并判断这次读数**可不可信**。
//
//   为什么需要它：CW2017 驱动的「就绪」判据（bsp_battery.c 的 cw_wait_soc_ready）
//   是 `soc <= 100`。而芯片**刚被重启**时 SOC 寄存器本来就是 0 —— 0 也满足该条件，
//   于是它在芯片还没开始算的时候就宣布「就绪」，把一个**占位 0** 当真值交出来。
//   那个判据区分不了「算完了、确实 0%」与「还没开始算、暂时 0」。
//
//   ★★ 判据（r56，2026-09-29）：**时间维度** ——
//     从「芯片最近一次上电」算起 WARMING_WINDOW_MS 内，SOC ≤ 3 一律判 WARMING。
//
//      依据：CW2017 官方 datasheet 写明 **No Sense Resistor Required** ——
//      这颗芯片**没有采样电阻、不是库仑计**，只测电压再拿一份电池模型反推 SOC。
//      芯片一上电，SOC 就停在 0、要用当前电压重新收敛；这段读数与电池实际余量
//      无关，**一律不可信**。
//
//      ⚠ r55 用的是「电压交叉校验」（SOC ≤ 3 且 mV ≥ 3600），已废弃：
//        隔夜 + 低温时电压本来就低，判据会认为「自洽」而放行占位 0
//        （09-29 早上真机漏出来的正是这一条）。时间维度不受电压漂移影响。
//      ⚠ 不掩盖真低电：窗口一过照常显示，真没电照样红 0% + 低电告警。
//      ⚠ 窗口自动重置：自愈重跑 bsp_battery_init() 后芯片又刚上电，
//        窗口从那一刻重新计时（否则自愈后立刻把新占位 0 报成 OK）。
//
//   soc_out / mv_out 允许传 NULL；读不到时写 -1。
//   ⚠ 本函数会走 I2C —— 调用方**必须**先拿 fa_batt_try_lock() 成功。
fa_batt_state_t fa_batt_read(int *soc_out, int *mv_out);

// ★★ 2026-10-04（r57，候选 2）：**"读不到"要能在界面上认账**。
//
//   病灶：连续读失败时 batt_show(-1) 把数字**清空**、图标不动（默认满格）
//   ⇒「满格图标 + 空白」既可能是"没读到"，也可能是"确实没画过"，
//     玩家和排查的人都**分不出来**（09-30 诊断 §1：满格图标是默认值，不携带信息）。
//
//   判据：看护任务里**连续 UNKNOWN_HEAL_FAILS 轮自愈都没成功** ⇒ 返回 true。
//   界面据此把那一格显示成 "--%" 而不是空白（`-` 与 `%` 都是 ASCII，字库必然有）。
//   ⚠ 只读一个 bool，不加锁（与 s_req 同策）；读到旧值最多让界面晚半秒切换。
bool fa_batt_unknown(void);
