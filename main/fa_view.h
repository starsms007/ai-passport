//
// 键位：
//   ↑ / ↓ 短按 = 翻上一条 / 下一条（翻到头绕回）
//   ● 短按    = 出册。**唯一的例外**：停在「接猫罐头」那一格时是**进游戏**
//   ● 长按    = **把这一条设成主页的风景**；翻到「家」就是回家
//
// ★ 2026-09-19（第十轮）新增一格：**「接猫罐头」**（永远在序列里，排在「家」后面）。
//   用户原话：「设计一个小游戏，放在收藏，跟明信片一样，可以让人选」。
//   它是一格**动作入口**，和「旅行中」同类；封面铺的是当前挂着的那张风景。
//   ⚠ 序列容量因此从 26 涨到 27（fa_view.c 的 s_dex_list）——
//     **数给小了就是越界写**，而那是全局数组旁边的内存，不会当场报错。
//
// ★ 2026-09-19（第九轮）新增一格：**「旅行中」**（只在 FA_AWAY 期间进序列，排第一）。
//   用户原话：「短按进入收藏，此时收藏里面设置一个回到旅行界面」。
//   它不是一个可挂的风景，是一格动作入口：● 短按出册 = 回到旅行界面
//   （FA_AWAY 状态自己会把旅行面板亮出来，所以这里不需要额外动作）。
//   长按它无效（fa_view_dex_ok_long 里给一句「回去之后再换风景」）。
//   ⚠ 序列容量因此从 25 涨到 26（fa_view.c 的 s_dex_list）——
//     带满 24 张明信片去旅行时正好 26 条，少一格就是越界写。
