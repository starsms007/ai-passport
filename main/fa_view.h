void fa_view_menu_ok(void);              // ● 短按：进入该格游戏 / 弹「还差几张」
// ★★ 2026-09-19（第十七轮）新增：● **长按** = 从选择页退回收藏册。
//   用户原话：「小游戏主界面要写"长按返回"。」
