//   「收藏里面就是明信片和家，把家当成一种一张明信片。」
//     序列 = 「家」（永远排第一） + 已到手的明信片（按景点号）
//     家       -> 家的底图缩到 11/16 放进图位；长按 ● 就是回家（小猫恢复动态）
//     明信片   -> 和「到达卡」**一字不差**的同一套画法（176x220 原图、scale 256）
