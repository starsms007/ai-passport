// main/fa_view.h —— 《去远方》界面层
//
// ★ 2026-09-19（第四次改版）设计取舍变了：主页面**不再用图元搭**，改成一张整图。
//   原话：「首页再重新渲染一张图片，不要再用色块了。类似明信片的风格。」
//   所以首页是 fa_res_home（240x320，素材侧 agent="scene-bg"，1:1 铺满），
//   猫是叠在它上面的精灵。
//
//   ★★ 2026-09-19（第十轮）：**「旅行中」不再是一种画面**。
//     挂风景铺的是那张 240x320 的**无猫**底图（fa_res_nocat_*），**旅行中也是它** ——
//     用户看过实机之后改了口径：「本来想着旅行中用有猫图，但是感觉效果不是很好，
//     旅行中也换成无猫版吧，跟小猫在家的时候一样，把小猫的动态效果放上面。」
//     于是「一张底图 + 我们自己的猫」成了全文件唯一一种画法，
//     旧版那层「176x220 带猫明信片放大 1.5 倍铺屏」整层删除。
//     （明信片那张**带猫**的图照旧在用 —— 收藏册和到达卡一直是它。）
//     顺带一个副作用：旅行时画面里**看不出「猫出去了」**，猫还在原地溜达。
//     这是刻意的取舍，用户要的是画面好看，不是叙事上猫必须消失。
//
//   ★★ 2026-09-19（第十一轮）补的一条 —— 上一轮**没做到**它自己写下的这句话：
//     实机反馈「目前旅行时候，好像动态小猫没有出现呀」。
//     根因不在猫的显隐（cat_sync 早就不藏它了），而在**坐标**：
//     出发那趟走完时 SEQ_WALKOUT 把 s_cat_x 停在 SCR_W(=240)，
//     也就是整只猫在屏幕右**外侧**；而旅行中原本没有任何一段代码把它搬回来
//     （default 分支只认 FA_HOME）⇒ 猫老老实实待在画面外，一帧都没出现过。
//     ⇒ 现在 FA_AWAY 分支里负责归位，并且**待机/溜达那套状态机对旅行中同样开着**，
//       这才是上面那句「把小猫的动态效果放上面」真正落地。
//     ⚠ 这条约定的成对关系写在两处：SEQ_WALKOUT 的结尾、FA_AWAY 的分支，
//       改任意一处都要回头看另一处。漏掉是**静默**的（不报错、猫就是不出现）。
//
//   ★ 2026-09-19（第五次）：叠在底图上的精灵**从「小屋 + 13 件小院道具 + 猫」
//     收成只剩猫**。新底图（像素-白天）画里自带房子，再叠精灵屋就是两栋房子重影；
//     那 13 件道具连同「布置小院」这个玩法一起按用户要求删除。
//
//   ★ 旧版首页是**程序化图元**搭的（sky/sun/cloud/hill/river/grass/bush 那十二组），
//     第四次改版整组删除。下面「历史的理由」那两条就是解释它当年为什么长那样。
//
//   历史的理由留在这儿备查（它解释了为什么曾经全是图元）：
//     1. 一张 240x320 的 ARGB8888 背景就是 300KB，比 18 组动画加起来还贵；
//        —— 现在用 RGB565（2 字节/px，无 alpha）只有 153,600 字节，负担得起；
//     2. 用图元搭的场景可以按昼夜换色（改 bg_color 而已），换成图就得备两套图；
//        —— 昼夜系统已按用户要求整个删除，改成一层的遮罩（旅行时压暗）。
//
// 所有函数都必须在 bsp_lvgl_lock() 内调用。
