//     MENU_CELL_LB_Y / MENU_CELL_SB_Y **一起改了**（只动一个会压字，不报错）。
//
//   「未解锁怎么显示」这条**三轮来回**，全留在这儿，防下次又推回去：
//     ~~第十六轮：不写游戏名，写「未解锁」，给人神秘感~~
//     ~~第十七轮：照设计稿**照写游戏名**，只把整张卡压暗~~
//     第十八轮：**写「未解锁」**（= 回到十六轮的口径，但**图标保留**、压暗一半）
//   ⇒ 以**最近一次点名**为准。要只说名字那一栏，只改 menu_refresh() 里那一行。
//
// 层级：收藏册（「小游戏」那一格）-> **选择页** -> 游戏本身。三层递进，
//       建序 = 图层序（见 fa_view_init / build_menu 那一段）。
