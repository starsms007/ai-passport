void fa_view_menu_back(void);

// ---- 小游戏「接猫罐头」（2026-09-19 第十轮新增）----
//
// 用户原话：「设计一个小游戏，放在收藏，跟明信片一样，可以让人选，小游戏就使用
//   用户选择的背景，游戏方式就是从上面掉下来猫罐头，让小猫去接，使用上下键，
//   每局15秒，接到超过一定数量，就给1-3个猫罐头，让人旅行等待的时候能有的玩。」
//
// 入口：收藏册里**「小游戏」那一格**（排在「家」后面）-> 选择页 -> 这一局。
//       ★★ 第十六轮起「接猫罐头」不再是册子里唯一的一格：那一格变成了
//          **四个游戏的总入口**（选择页），接猫罐头只是选择页的第一行。
//       ★ 它永远解锁（门槛 0），所以「闭着眼按 ● 也一定有的玩」这条仍然成立。
// 背景：**当前挂着的那处风景**（fa_scene()）—— 想换背景就翻到某张明信片长按 ●。
//       刻意不另设「游戏背景」这个存档项：玩家心里只有一个"我选的背景"，
//       存两份迟早出现「册子里换了、游戏里还是旧的」。
// 键位：↑ = 往左，↓ = 往右；● 短按 = 结算后回册；● 长按 = 提前结束并结算（奖励照给）。
//
// ★★ 为什么 ↑↓ 是「左右」而不是「上下」：
//   板子上只有 ↑ ↓ ● 三颗键（main.c 的 K_UP / K_DOWN / K_OK），**没有左右键**。
//   而接落物这个玩法必须能做水平位移，否则罐头横向随机落、猫只能在原地挨砸。
//   这是三键硬件上做这类小游戏的通行做法，**已跟用户确认过**。
//
// ★ 奖励（用户选的那一档）：接 0-3 个 -> 0；4-6 -> 1 个；7-9 -> 2 个；10+ -> 3 个。
//   落空不扣分 —— 它是「等待时有的玩」的消遣，不是竞技。
//
// ⚠ 按键接入有一个**顺序陷阱**（在 main.c）：小游戏的抬手事件必须处理在
//   `on_release()` 的 `if (was_long) return;` **之前**。长按 ↑ 会先触发 EV_LONG，
//   抬手时 was_long 为真；要是按常规流程直接 return，「松开方向键」这件事就丢了，
//   猫会朝那个方向一路走到局终。
bool fa_view_mini_open(void);                  // 查询：在游戏里吗
// 开一局。game 取 fa_view.c 里的 GAME_*（0 接猫罐头 / 1 打兔子 / 2 猜拳 / 3 翻牌）。
// ★★ 第十六轮：签名从 `(void)` 改成 `(int game)`。
//   ⚠ **调用点只有一个**：fa_view_menu_ok()。册子那一格已经改成开选择页了，
//     别再从这里直接开某一局 —— 那样另外三个游戏就没入口了。
//   越界的 game 由实现侧兜（会退回选择页），调用方不用自己校验。
void fa_view_mini_show(int game);
void fa_view_mini_hold(int dir, bool down);    // dir: -1 = ↑，+1 = ↓（含义按游戏分派）
void fa_view_mini_ok(void);                    // ● 短按：按游戏分派（猜拳出拳 / 翻牌翻开 / 结算回选择页）
void fa_view_mini_end_now(void);               // ● 长按：提前结束本局并按当前分数结算

